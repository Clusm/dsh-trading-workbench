/**
 * Process-level build / load identity (05 §3.1 N02, 01 §5.1 single field table).
 *
 * Three names and only three names are exported to the outside world:
 *   buildId         - which Host load is running (changes on every reload)
 *   configRevision  - which saved LLM config is in effect (null = never saved)
 *   chain_version   - the AI chain contract version (constants.js)
 *
 * Honesty boundary (01 §5.1): these are *process* facts. Reading an old round
 * shows the current load identity, NOT the build that produced that round. A
 * per-round build snapshot is P1-7 and must never be faked from the live value.
 *
 * Load identity must not depend on this module being re-evaluated: a Host
 * reload may reuse a cached ESM instance for an unchanged file, which froze
 * `loaded_at` at the previous load and made /health lie about which load was
 * running (observed 2026-11-13: probe route was new while buildId stayed 22h
 * old). `index.js#apply` therefore calls `markHostLoad()` on every apply, and
 * that call is what advances the identity.
 */

import { createHash } from 'node:crypto'
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

import { CHAIN_VERSION, PROMPT_VERSIONS } from './ai/constants.js'

/**
 * F1 (§5.1 / §8·F): "实际加载版本可核对" needs two separate facts.
 *
 *   release_id / release_source_digest - which *source tree* was packaged
 *     (generated by scripts/build-release.mjs into plugin/.release.json)
 *   loaded_at                          - when *this process* loaded the code
 *
 * The manifest is read exactly once, at module evaluation, and the value is
 * then kept in memory. Nothing re-reads the file per request: a process must
 * never claim to be running code it has not loaded, and a freshly written
 * manifest must not make /health look newer than the running process.
 */
// The manifest is a deployment artifact written by scripts/build-release.mjs.
// It lives under scripts/ (next to the tool that produces it) so the plugin
// package itself stays free of generated files.
const RELEASE_MANIFEST_URL = new URL('../../scripts/.release/plugin-release.json', import.meta.url)

function readReleaseManifest() {
  const manifestPath = fileURLToPath(RELEASE_MANIFEST_URL)
  const empty = {
    release_id: null,
    source_digest: null,
    plugin_version: null,
    generated_at: null,
    file_count: null,
    source: 'absent',
    path: manifestPath,
  }
  let raw
  try {
    raw = JSON.parse(readFileSync(manifestPath, 'utf8'))
  } catch (error) {
    if (error?.code === 'ENOENT') return empty
    return { ...empty, source: 'unreadable', error: String(error?.code ?? error?.message ?? error) }
  }
  const releaseId = typeof raw?.release_id === 'string' && raw.release_id.trim() ? raw.release_id.trim() : null
  if (!releaseId) return { ...empty, source: 'invalid' }
  return {
    release_id: releaseId,
    source_digest: typeof raw?.source_digest === 'string' && raw.source_digest ? raw.source_digest : null,
    plugin_version: typeof raw?.plugin_version === 'string' ? raw.plugin_version : null,
    generated_at: typeof raw?.generated_at === 'string' ? raw.generated_at : null,
    file_count: Number.isInteger(raw?.file_count) ? raw.file_count : null,
    source: 'manifest',
    path: manifestPath,
  }
}

// Captured once for the life of this module instance. A Host reload may reuse a
// cached ESM instance; in that case the *load* identity (loaded_at/buildId)
// still advances via markHostLoad(), while the release identity honestly stays
// the one that was loaded.
const RELEASE = readReleaseManifest()

// Digest of the entry configuration: a changed chain/prompt set changes the
// digest, so "same buildId" cannot hide a code change in those files.
const ENTRY_DIGEST = createHash('sha256')
  .update(CHAIN_VERSION)
  .update(JSON.stringify(PROMPT_VERSIONS))
  .digest('hex')
  .slice(0, 8)

const PROMPT_SET = `prompts/${ENTRY_DIGEST}`

function stamp(from = new Date()) {
  return from.toISOString().replace(/[-:]/g, '').replace(/\.\d+Z$/, 'Z')
}

// Seeded at module evaluation; advanced by markHostLoad() on every apply().
let loadedAt = new Date().toISOString()
let loadSeq = 0
let buildId = `twb-${stamp(new Date(loadedAt))}-${ENTRY_DIGEST}`

// 02 owns the semantics: data/llm-config.json.revision. Until a config is
// actually saved this is null and the UI must say "未保存" instead of 0.
let loadedConfigRevision = null

/** Called by the Host once a configuration has been resolved and is in effect. */
export function setLoadedConfigRevision(value) {
  loadedConfigRevision = Number.isInteger(value) && value >= 0 ? value : null
  return loadedConfigRevision
}

/**
 * Mark a new Host load. Called from `apply()` on every (re)load so the exposed
 * identity always names the load that is actually serving requests, even when
 * ESM cached this module. The sequence keeps two loads in the same second
 * distinguishable.
 */
export function markHostLoad(now = Date.now()) {
  loadSeq += 1
  loadedAt = new Date(now).toISOString()
  buildId = `twb-${stamp(new Date(loadedAt))}-${ENTRY_DIGEST}`
  return currentBuild()
}

export function currentBuild() {
  return {
    buildId,
    configRevision: loadedConfigRevision,
    chain_version: CHAIN_VERSION,
    loaded_at: loadedAt,
    prompt_set: PROMPT_SET,
    // Source release (packaged artifact) — never derived from the load time.
    release_id: RELEASE.release_id,
    release_source: RELEASE.source,
    release_source_digest: RELEASE.source_digest,
    release_generated_at: RELEASE.generated_at,
    plugin_version: RELEASE.plugin_version,
    release_file_count: RELEASE.file_count,
  }
}

/** Absolute path of the release manifest this process captured at load. */
export function releaseManifestPath() {
  return RELEASE.path
}

export const BUILD = Object.freeze({
  chain_version: CHAIN_VERSION,
  prompt_set: PROMPT_SET,
})

/** Number of Host loads observed by this process (diagnostics only). */
export function hostLoadSeq() {
  return loadSeq
}
